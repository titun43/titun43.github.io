/**
 * Apply translations to all elements with data-i18n attribute.
 * Called after DOMContentLoaded and whenever language changes.
 */
function applyTranslations(lang) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (I18N[key] && I18N[key][lang]) {
      el.textContent = I18N[key][lang];
    }
  });
  // Update <html lang="...">
  document.documentElement.lang = lang;
}

/**
 * Get current language from localStorage, fallback to 'en'.
 */
function getCurrentLang() {
  return localStorage.getItem('lt-lang') || 'en';
}

/**
 * Set language, save to localStorage, apply.
 */
function setLanguage(lang) {
  localStorage.setItem('lt-lang', lang);
  applyTranslations(lang);
  // Update dropdown label
  const labelEl = document.getElementById('lang-current-label');
  if (labelEl) {
    const labels = { en: 'EN', bn: 'বাং', hi: 'हिं', as: 'অসম' };
    labelEl.textContent = labels[lang] || 'EN';
  }
}

/**
 * Theme toggle (dark/light).
 * Saves preference to localStorage.
 */
function getCurrentTheme() {
  return localStorage.getItem('lt-theme') || 'dark';
}
function setTheme(theme) {
  localStorage.setItem('lt-theme', theme);
  document.documentElement.setAttribute('data-theme', theme);
  const icon = document.getElementById('theme-icon');
  if (icon) {
    icon.textContent = theme === 'dark' ? '🌙' : '☀️';
  }
}
function toggleTheme() {
  const current = getCurrentTheme();
  setTheme(current === 'dark' ? 'light' : 'dark');
}

/**
 * Initialise on page load.
 */
document.addEventListener('DOMContentLoaded', () => {
  // Language
  setLanguage(getCurrentLang());

  // Theme
  setTheme(getCurrentTheme());

  // Theme toggle button
  const themeBtn = document.getElementById('theme-toggle');
  if (themeBtn) {
    themeBtn.addEventListener('click', toggleTheme);
  }

  // Language dropdown
  const langBtn = document.getElementById('lang-toggle');
  const langMenu = document.getElementById('lang-menu');
  if (langBtn && langMenu) {
    langBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      langMenu.classList.toggle('show');
    });
    document.addEventListener('click', (e) => {
      if (!langBtn.contains(e.target) && !langMenu.contains(e.target)) {
        langMenu.classList.remove('show');
      }
    });
    document.querySelectorAll('.lang-option').forEach(opt => {
      opt.addEventListener('click', () => {
        const lang = opt.getAttribute('data-lang');
        setLanguage(lang);
        langMenu.classList.remove('show');
      });
    });
  }

  // ===== REVIEWS TAB SWITCHING =====
  const reviewTabs = document.querySelectorAll('.reviews-tab');
  const reviewPanels = document.querySelectorAll('[data-reviews-panel]');
  if (reviewTabs.length && reviewPanels.length) {
    reviewTabs.forEach(tab => {
      tab.addEventListener('click', () => {
        const target = tab.getAttribute('data-reviews-tab');
        // Update tab active state
        reviewTabs.forEach(t => t.classList.remove('active'));
        tab.classList.add('active');
        // Show/hide panels
        reviewPanels.forEach(panel => {
          if (panel.getAttribute('data-reviews-panel') === target) {
            panel.style.display = '';
          } else {
            panel.style.display = 'none';
          }
        });
      });
    });
  }
});
